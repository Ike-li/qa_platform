def test_quality_ops_records_current_gate_summary_freshness_evidence():
    latest_row = _quality_ops_row(
        "| 2026-05-30 | collect-only `tests/integration` 212 tests"
    )

    for count in STALE_DOCS_CONTRACT_PASS_COUNTS:
        assert (
            f"`tests/unit/test_release_quality_docs_contract.py` {count} passed"
            not in latest_row
        )
    for count in STALE_COVERAGE_UNIT_COUNTS:
        assert f"coverage unit {count} passed" not in latest_row
    for percentage in STALE_TOTAL_COVERAGE_PERCENTAGES:
        assert f"total {percentage}" not in latest_row
    for percentage in STALE_STATEMENT_COVERAGE_PERCENTAGES:
        assert f"statements {percentage}" not in latest_row
    for percentage in STALE_BRANCH_COVERAGE_PERCENTAGES:
        assert f"branches {percentage}" not in latest_row

    assert "85.07%" not in latest_row
    assert "`docs/backend-test-audit.md` 的“当前基线结果”仍停在旧" not in latest_row
